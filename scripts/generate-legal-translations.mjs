import { LANGS, UI, PRIVACY, TERMS } from "./legal-source.mjs";
import { writeFileSync } from "node:fs";

const API_KEY = process.env.LOVABLE_API_KEY;
if (!API_KEY) {
  console.error("Missing LOVABLE_API_KEY");
  process.exit(1);
}

const ENDPOINT = "https://ai.gateway.lovable.dev/v1/chat/completions";
const MODEL = "google/gemini-2.5-flash";

async function translateDoc(doc, langCode, langLabel) {
  const payload = {
    ui: UI,
    title: doc.title,
    lastUpdatedLabel: UI.lastUpdatedLabel,
    sections: doc.sections,
  };
  const sys =
    "You are a professional legal/app-store localization translator. Translate ALL human-readable strings in the given JSON into " +
    langLabel +
    " (" +
    langCode +
    "). Rules: keep the EXACT same JSON shape and keys; translate only the string VALUES; do NOT translate email addresses, brand/product names (Atomic Fusion Rush, Atomic Fusion Lifetime, EA Consulting, RevenueCat, Apple App Store, App Store, Pro), or numbers/dates; keep punctuation natural for the target language; return ONLY valid minified JSON, no markdown, no commentary.";
  const res = await fetch(ENDPOINT, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${API_KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      model: MODEL,
      messages: [
        { role: "system", content: sys },
        { role: "user", content: JSON.stringify(payload) },
      ],
      temperature: 0.2,
    }),
  });
  if (!res.ok) {
    throw new Error(`HTTP ${res.status}: ${await res.text()}`);
  }
  const data = await res.json();
  let content = data.choices?.[0]?.message?.content ?? "";
  content = content.trim().replace(/^```json\s*/i, "").replace(/^```\s*/i, "").replace(/```$/i, "").trim();
  return JSON.parse(content);
}

function buildEnglish(doc) {
  return {
    title: doc.title,
    lastUpdatedLabel: UI.lastUpdatedLabel,
    sections: doc.sections,
  };
}

async function build(doc) {
  const out = {};
  for (const { code, label } of LANGS) {
    if (code === "en") {
      out[code] = buildEnglish(doc);
      console.error(`  en ok`);
      continue;
    }
    let attempt = 0;
    while (true) {
      try {
        out[code] = await translateDoc(doc, code, label);
        console.error(`  ${code} ok`);
        break;
      } catch (e) {
        attempt++;
        console.error(`  ${code} attempt ${attempt} failed: ${e.message}`);
        if (attempt >= 3) throw e;
        await new Promise((r) => setTimeout(r, 1500 * attempt));
      }
    }
  }
  return out;
}

console.error("Translating privacy...");
const privacy = await build(PRIVACY);
console.error("Translating terms...");
const terms = await build(TERMS);

const file = `// AUTO-GENERATED by scripts/generate-legal-translations.mjs. Do not edit by hand.

export type LegalLang =
${LANGS.map((l) => `  | ${JSON.stringify(l.code)}`).join("\n")};

export type LegalSection = {
  heading: string;
  body: string[];
  list?: string[];
};

export type LegalDoc = {
  title: string;
  lastUpdatedLabel: string;
  sections: LegalSection[];
};

export const LEGAL_LANGUAGES: { code: LegalLang; label: string; dir: "ltr" | "rtl" }[] = [
${LANGS.map((l) => `  { code: ${JSON.stringify(l.code)}, label: ${JSON.stringify(l.label)}, dir: ${JSON.stringify(l.code === "ar" ? "rtl" : "ltr")} },`).join("\n")}
];

export const LEGAL_LAST_UPDATED_DATE = ${JSON.stringify(PRIVACY.lastUpdated)};

export const PRIVACY_CONTENT: Record<LegalLang, LegalDoc> = ${JSON.stringify(privacy, null, 2)};

export const TERMS_CONTENT: Record<LegalLang, LegalDoc> = ${JSON.stringify(terms, null, 2)};
`;

writeFileSync("src/content/legalDocs.generated.ts", file);
console.error("Wrote src/content/legalDocs.generated.ts");
